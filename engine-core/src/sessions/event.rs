//! Append-only session event log.
//!
//! Every significant action in a ReinCore session - LLM calls, tool calls,
//! tool results, summaries, tier transitions, loop interventions, checkpoints
//! - is recorded as an immutable [`SessionEvent`] with a monotonically
//! increasing sequence number. The [`EventStore`] trait is the persistence
//! contract; backends (SQLite, Postgres, in-memory) implement it and the
//! memory manager, circuit breaker, and checkpoint system all read from it
//! to reconstruct session state.

use crate::error::EngineResult;
use crate::models::{ChatMessage, ToolCall, ToolResult};
use crate::routing::ClassificationTelemetry;
use crate::workflow::ContextAdjustment;
use async_trait::async_trait;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use uuid::Uuid;

/// A single event in the canonical, append-only session event log.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct SessionEvent {
    pub session_id: Uuid,
    pub seq: i64,
    pub event_type: SessionEventType,
    pub payload: serde_json::Value,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub cost_cents: Option<i64>,
    pub created_at: DateTime<Utc>,
}

impl SessionEvent {
    /// No-cost events contribute zero; explicit unknown estimates remain unknown.
    pub fn amount_nano_usd(&self) -> Option<i64> {
        if let Some(cost) = self.payload.get("cost") {
            cost.get("amount_nano_usd").and_then(|v| v.as_i64())
        } else {
            self.cost_cents
                .unwrap_or(0)
                .checked_mul(crate::pricing::NANO_USD_PER_CENT)
        }
    }
}

