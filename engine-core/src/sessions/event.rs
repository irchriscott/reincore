/// Compact, query-friendly projection of an LLM event used by request-time
/// task resolution. Keeping this separate from the audit payload prevents a
/// task lookup from loading every historical provider transcript.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
pub struct TaskEventProjection {
    pub session_id: Uuid,
    pub seq: i64,
    pub request_group_id: Option<String>,
    pub task_id: Option<String>,
    pub task_name: Option<String>,
    pub task_type: Option<String>,
    pub user_prompt: Option<String>,
    pub response_text: Option<String>,
    pub response_has_tool_calls: bool,
    pub input_tokens: u64,
    pub output_tokens: u64,
    pub cost_cents: Option<i64>,
    pub created_at: DateTime<Utc>,
}

impl TaskEventProjection {
    pub const MAX_TEXT_CHARS: usize = 8_192;

    /// Extract the actual request before applying the preview budget. Client
    /// context can be much larger than that budget and precede the user text.
    pub fn prompt_from_request_messages(value: &serde_json::Value) -> Option<String> {
        let messages = serde_json::from_value::<Vec<ChatMessage>>(value.clone()).ok()?;
        messages.iter().rev().find_map(|message| {
            if !message.role.eq_ignore_ascii_case("user") || message.tool_call_id.is_some() {
                return None;
            }
            let text = message.full_text();
            crate::user_content::session_user_request(&text)
                .map(|prompt| truncate_text(prompt.to_owned(), Self::MAX_TEXT_CHARS))
        })
    }

    /// Old projections may contain only a clipped context wrapper. Readers
    /// selectively supply the original messages to repair those previews.
    pub fn recover_user_prompt(
        stored: Option<String>,
        original: Option<serde_json::Value>,
    ) -> Option<String> {
        original
            .as_ref()
            .and_then(Self::prompt_from_request_messages)
            .or_else(|| {
                stored.and_then(|text| {
                    crate::user_content::session_user_request(&text).map(str::to_owned)
                })
            })
    }

    pub fn from_event(event: &SessionEvent) -> Option<Self> {
        if event.event_type != SessionEventType::LlmCall {
            return None;
        }
        let user_prompt = event
            .payload
            .get("request_messages")
            .and_then(Self::prompt_from_request_messages);
        let response = event
            .payload
            .get("response_message")
            .and_then(|value| serde_json::from_value::<ChatMessage>(value.clone()).ok());
        let response_text = response.as_ref().and_then(|message| {
            let text = message.full_text();
            (!text.trim().is_empty()).then(|| truncate_text(text, Self::MAX_TEXT_CHARS))
        });
        let response_has_tool_calls = response
            .as_ref()
            .and_then(|message| message.tool_calls.as_deref())
            .is_some_and(|calls| !calls.is_empty());
        Some(Self {
            session_id: event.session_id,
            seq: event.seq,
            request_group_id: payload_text(&event.payload, "request_group_id"),
            task_id: payload_text(&event.payload, "task_id"),
            task_name: payload_text(&event.payload, "task_name"),
            task_type: payload_text(&event.payload, "task_type"),
            user_prompt,
            response_text,
            response_has_tool_calls,
            input_tokens: event
                .payload
                .get("input_tokens")
                .and_then(serde_json::Value::as_u64)
                .unwrap_or(0),
            output_tokens: event
                .payload
                .get("output_tokens")
                .and_then(serde_json::Value::as_u64)
                .unwrap_or(0),
            cost_cents: event.cost_cents,
            created_at: event.created_at,
        })
    }

    /// Convert the projection into the small compatibility event consumed by
    /// the existing task grouping logic.
    pub fn into_event(self) -> SessionEvent {
        let request_messages = self
            .user_prompt
            .map(|content| {
                vec![ChatMessage {
                    provider_state: None,
                    role: "user".to_string(),
                    content: Some(crate::models::MessageContent::Text(content)),
                    tool_calls: None,
                    tool_call_id: None,
                    name: None,
                }]
            })
            .unwrap_or_default();
        let response_message = ChatMessage {
            provider_state: None,
            role: "assistant".to_string(),
            content: self.response_text.map(crate::models::MessageContent::Text),
            tool_calls: self.response_has_tool_calls.then(|| {
                vec![ToolCall {
                    id: "projection".to_string(),
                    call_type: "function".to_string(),
                    function: crate::models::FunctionCall {
                        name: "projection".to_string(),
                        arguments: "{}".to_string(),
                    },
                }]
            }),
            tool_call_id: None,
            name: None,
        };
        SessionEvent {
            session_id: self.session_id,
            seq: self.seq,
            event_type: SessionEventType::LlmCall,
            payload: serde_json::json!({
                "request_messages": request_messages,
                "response_message": response_message,
                "request_group_id": self.request_group_id,
                "task_id": self.task_id,
                "task_name": self.task_name,
                "task_type": self.task_type,
                "input_tokens": self.input_tokens,
                "output_tokens": self.output_tokens,
            }),
            cost_cents: self.cost_cents,
            created_at: self.created_at,
        }
    }
}

/// Indexed association between an external tool call and its request group.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct ToolCallLink {
    pub session_id: Uuid,
    pub tool_call: ToolCall,
    pub request_group_id: Option<String>,
    pub origin_llm_call_seq: Option<i64>,
    pub delegation_profile: Option<String>,
    pub requested_at: DateTime<Utc>,
}

fn truncate_text(value: String, max_chars: usize) -> String {
    value.chars().take(max_chars).collect()
}

fn payload_text(payload: &serde_json::Value, key: &str) -> Option<String> {
    payload
        .get(key)
        .and_then(serde_json::Value::as_str)
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(str::to_string)
}

/// Persist only the current user turn in an LLM audit event. Provider requests
/// often contain the complete conversation, so cloning them into every event
/// makes storage grow quadratically. Canonical response and tool events retain
/// the rest of the replayable turn history.
pub fn compact_audit_request_messages(messages: &[ChatMessage]) -> Vec<ChatMessage> {
    messages
        .iter()
        .rev()
        .find(|message| {
            message.role.eq_ignore_ascii_case("user")
                && message.tool_call_id.is_none()
                && message.has_user_content()
        })
        .cloned()
        .into_iter()
        .collect()
}

/// Build the indexed tool-call associations carried by an event.
pub fn tool_call_links_from_event(event: &SessionEvent) -> Vec<ToolCallLink> {
    let group = payload_text(&event.payload, "request_group_id");
    let profile = payload_text(&event.payload, "delegation_profile");
    match event.event_type {
        SessionEventType::LlmCall => event
            .payload
            .pointer("/response_message/tool_calls")
            .and_then(serde_json::Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(|raw| serde_json::from_value::<ToolCall>(raw.clone()).ok())
            .map(|tool_call| ToolCallLink {
                session_id: event.session_id,
                tool_call,
                request_group_id: group.clone(),
                origin_llm_call_seq: Some(event.seq),
                delegation_profile: profile.clone(),
                requested_at: event.created_at,
            })
            .collect(),
        SessionEventType::ToolCall => event
            .payload
            .get("tool_call")
            .and_then(|raw| serde_json::from_value::<ToolCall>(raw.clone()).ok())
            .map(|tool_call| {
                vec![ToolCallLink {
                    session_id: event.session_id,
                    tool_call,
                    request_group_id: group,
                    origin_llm_call_seq: event
                        .payload
                        .get("origin_llm_call_seq")
                        .and_then(serde_json::Value::as_i64),
                    delegation_profile: profile,
                    requested_at: event
                        .payload
                        .get("requested_at")
                        .and_then(serde_json::Value::as_str)
                        .and_then(|value| DateTime::parse_from_rfc3339(value).ok())
                        .map(|value| value.with_timezone(&Utc))
                        .unwrap_or(event.created_at),
                }]
            })
            .unwrap_or_default(),
        _ => Vec::new(),
    }
}

