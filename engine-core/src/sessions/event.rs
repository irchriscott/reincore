/// Event types used by the memory manager and downstream subsystems.
#[derive(Clone, Copy, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum SessionEventType {
    /// Bounded, attributed execution state for restart and context rollover.
    Continuation,
    /// Grounded task decisions, independent of provider replay.
    TaskDecision,
    /// SDK-reported batch lifecycle, model results, and local tool activity.
    Batch,
    /// An outbound LLM call (request + response metadata).
    LlmCall,
    /// Billed title/prewarm request, excluded from conversation context.
    AuxiliaryCall,
    /// A tool call issued by the agent.
    ToolCall,
    /// The result returned by a tool/MCP server.
    ToolResult,
    /// An episodic summary generated by the memory manager.
    Summary,
    /// A budget tier transition.
    TierChange,
    /// A loop intervention injected by the circuit breaker.
    LoopIntervention,
    /// A checkpoint created at a hard stop.
    Checkpoint,
    /// A checkpoint token consumed by a successful resume attempt.
    CheckpointRedeemed,
    /// A grounded hallucination or no-progress agent health finding.
    AgentHealth,
    /// A physical session completed and linked to a fresh successor.
    SessionRollover,
    /// A session was explicitly marked complete by its caller or operator.
    SessionCompleted,
    /// A display title changed asynchronously; never conversation context.
    TitleUpdated,
    /// A predictive pre-warming pass fired on a tier transition.
    /// Payload is a [`crate::prewarm::PreWarmOutcome`].
    PreWarm,
    /// The engine settings a request group ran with, recorded once when the
    /// group starts so a run can be explained after the fact. Diagnostic
    /// only; never conversation context.
    SettingsApplied,
}

